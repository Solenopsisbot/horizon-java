// Prints crates/horizon-native-java/src/neoforge_event_classes.rs: every NeoForge event class
// (every class that extends net.neoforged.bus.api.Event) in the jars given, with its superclass and
// the three facts NeoForge's bus (bus-8.0.5) reads from the class itself: `Modifier.isAbstract`,
// `ICancellableEvent.class.isAssignableFrom` and `IModBusEvent.class.isAssignableFrom`.
//
// Usage (any JDK with java.lang.classfile, 24+; the answer is read from class headers only):
//   java tools/neoforge_tables/EventClassTable.java bus-8.0.5.jar loader-12.0.12.jar \
//       neoforge-26.3.0.101-universal.jar > crates/horizon-native-java/src/neoforge_event_classes.rs
// The jars are the player's own NeoForge 26.3.0.101 install (`libraries/net/neoforged/...`); the
// output holds only class names and flags, never code.

import java.lang.classfile.ClassFile;
import java.lang.classfile.ClassModel;
import java.lang.reflect.AccessFlag;
import java.nio.file.Path;
import java.util.*;
import java.util.zip.ZipFile;

public class EventClassTable {
    record Header(String name, String superName, List<String> interfaces, boolean isAbstract, boolean isInterface) {}

    static final String EVENT = "net/neoforged/bus/api/Event";
    static final String CANCELLABLE = "net/neoforged/bus/api/ICancellableEvent";
    static final String MOD_BUS = "net/neoforged/fml/event/IModBusEvent";

    static final Map<String, Header> HEADERS = new HashMap<>();

    public static void main(String[] args) throws Exception {
        List<String> sources = new ArrayList<>();
        for (String jar : args) {
            sources.add(Path.of(jar).getFileName().toString());
            try (ZipFile zip = new ZipFile(jar)) {
                for (var entries = zip.entries(); entries.hasMoreElements(); ) {
                    var entry = entries.nextElement();
                    String path = entry.getName();
                    if (!path.endsWith(".class") || path.startsWith("META-INF/") || path.endsWith("module-info.class")) continue;
                    ClassModel model = ClassFile.of().parse(zip.getInputStream(entry).readAllBytes());
                    var flags = model.flags();
                    HEADERS.put(model.thisClass().asInternalName(), new Header(
                        model.thisClass().asInternalName(),
                        model.superclass().map(c -> c.asInternalName()).orElse(null),
                        model.interfaces().stream().map(c -> c.asInternalName()).toList(),
                        flags.has(AccessFlag.ABSTRACT),
                        flags.has(AccessFlag.INTERFACE)));
                }
            }
        }
        TreeMap<String, Header> events = new TreeMap<>();
        for (Header header : HEADERS.values()) {
            if (!header.isInterface() && extendsEvent(header.name())) events.put(header.name(), header);
        }
        StringBuilder out = new StringBuilder();
        out.append("//! NeoForge's event classes: each class that extends `net.neoforged.bus.api.Event` in\n");
        out.append("//! ").append(String.join(", ", sources)).append(",\n");
        out.append("//! with its superclass and what NeoForge's bus reads from the class (`Modifier.isAbstract`,\n");
        out.append("//! `ICancellableEvent.class.isAssignableFrom`, `IModBusEvent.class.isAssignableFrom`).\n");
        out.append("//!\n");
        out.append("//! Generated by `tools/neoforge_tables/EventClassTable.java`; do not edit. ").append(events.size()).append(" classes.\n\n");
        out.append("/// `Modifier.isAbstract(class.getModifiers())`.\n");
        out.append("pub(crate) const ABSTRACT: u8 = 1 << 0;\n");
        out.append("/// `ICancellableEvent.class.isAssignableFrom(class)`.\n");
        out.append("pub(crate) const CANCELLABLE: u8 = 1 << 1;\n");
        out.append("/// `IModBusEvent.class.isAssignableFrom(class)`: a mod-bus event.\n");
        out.append("pub(crate) const MOD_BUS: u8 = 1 << 2;\n\n");
        out.append("/// `(class, superclass, flags)`, sorted by class name.\n");
        out.append("#[rustfmt::skip]\n");
        out.append("pub(crate) const EVENT_CLASSES: &[(&str, &str, u8)] = &[\n");
        for (Header header : events.values()) {
            int flags = (header.isAbstract() ? 1 : 0)
                | (assignable(CANCELLABLE, header.name()) ? 2 : 0)
                | (assignable(MOD_BUS, header.name()) ? 4 : 0);
            out.append("    (\"").append(header.name()).append("\", \"")
                .append(header.superName() == null ? "" : header.superName()).append("\", ")
                .append(flags).append("),\n");
        }
        out.append("];\n");
        System.out.print(out);
    }

    static boolean extendsEvent(String name) {
        for (String at = name; at != null; ) {
            if (at.equals(EVENT)) return true;
            Header header = HEADERS.get(at);
            if (header == null) return false;
            at = header.superName();
        }
        return false;
    }

    /// `target.isAssignableFrom(name)` over the superclasses and every superinterface.
    static boolean assignable(String target, String name) {
        Deque<String> work = new ArrayDeque<>(List.of(name));
        Set<String> seen = new HashSet<>();
        while (!work.isEmpty()) {
            String at = work.pop();
            if (at.equals(target)) return true;
            if (!seen.add(at)) continue;
            Header header = HEADERS.get(at);
            if (header == null) continue;
            if (header.superName() != null) work.push(header.superName());
            header.interfaces().forEach(work::push);
        }
        return false;
    }
}
